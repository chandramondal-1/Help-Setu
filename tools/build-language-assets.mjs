/* Build i18n-extra.js and data-i18n.js from data/translations/auto/*.json.
   Run after tools/translate.py. */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createContext, runInContext } from 'node:vm';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const languages = JSON.parse(readFileSync(resolve(root, 'tools/languages.json'), 'utf8'));
const source = JSON.parse(readFileSync(resolve(root, 'data/translations/source.json'), 'utf8'));
const ctx = { window: {} };
createContext(ctx);
runInContext(readFileSync(resolve(root, 'data.js'), 'utf8'), ctx);
const DATA = ctx.window.HELPSETU_DATA;
const SERVICE = new Map(DATA.services.map((s) => [s.id, s]));

function setPath(obj, keys, value) {
  let cur = obj;
  for (let i = 0; i < keys.length; i++) {
    const k = keys[i];
    if (i === keys.length - 1) { cur[k] = value; return; }
    if (!cur[k] || typeof cur[k] !== 'object') cur[k] = {};
    cur = cur[k];
  }
}

const active = [];
const uiPacks = {};
const dataPacks = {};

for (const lang of languages) {
  if (!lang.google) {
    active.push({ ...lang, beta: false, curated: true });
    continue;
  }
  const file = resolve(root, `data/translations/auto/${lang.google}.json`);
  if (!existsSync(file)) { console.log('skip missing', lang.code); continue; }
  const pack = JSON.parse(readFileSync(file, 'utf8'));
  const values = Object.entries(pack.ui || {});
  const translated = values.filter(([k, v]) => v && v !== source.ui[k]).length;
  const coverage = values.length ? translated / values.length : 0;
  if (coverage < 0.5) {
    console.log(`skip ${lang.code}: only ${(coverage * 100).toFixed(0)}% translated`);
    continue;
  }
  const ui = {};
  for (const [key, value] of values) setPath(ui, key.split('.'), value);
  uiPacks[lang.code] = ui;
  dataPacks[lang.code] = pack;
  active.push({ ...lang, beta: true, curated: false });
  console.log(`${lang.code}: ${(coverage * 100).toFixed(0)}% UI translated`);
}

const meta = active.map((l) => ({
  code: l.code, native: l.native, english: l.english, locale: l.locale,
  dir: l.dir || 'ltr', curated: !!l.curated, beta: !!l.beta,
}));

const uiJs = `/* Generated by tools/build-language-assets.mjs — do not edit by hand. */
window.HELPSETU_LANGS = ${JSON.stringify(meta, null, 2)};
window.HELPSETU_I18N = Object.assign(window.HELPSETU_I18N || {}, ${JSON.stringify(uiPacks, null, 1)});
`;
writeFileSync(resolve(root, 'i18n-extra.js'), uiJs);

const dataJs = `/* Generated by tools/build-language-assets.mjs — do not edit by hand. */
(() => {
  const D = window.HELPSETU_DATA;
  if (!D) return;
  const T = ${JSON.stringify(dataPacks, null, 1)};
  for (const [lang, pack] of Object.entries(T)) {
    for (const c of D.categories) {
      const v = pack.categories?.[c.id];
      if (v) c.name[lang] = v;
    }
    for (const s of D.states) {
      const v = pack.states?.[s.code];
      if (v) s[lang] = v;
    }
    for (const it of D.intents) {
      const v = pack.intents?.[it.id];
      if (!v) continue;
      if (v.title) it.title[lang] = v.title;
      if (Array.isArray(v.phrases)) it.phrases[lang] = v.phrases;
      if (Array.isArray(v.steps)) it.steps[lang] = v.steps;
    }
    for (const s of D.services) {
      const v = pack.services?.[s.id];
      if (!v) continue;
      if (v.name) s.name[lang] = v.name;
      if (v.purpose) s.purpose[lang] = v.purpose;
      if (v.when) s.when[lang] = v.when;
      if (Array.isArray(v.steps)) s.steps[lang] = v.steps;
    }
  }
})();
`;
writeFileSync(resolve(root, 'data-i18n.js'), dataJs);

console.log(`Wrote i18n-extra.js and data-i18n.js with ${active.length} languages.`);
